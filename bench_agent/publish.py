"""Put the A/B result into the documents, by script, so no number is ever typed by hand.

    python -m bench_agent.publish runs/<ts>_ab_off runs/<ts>_ab_on

Writes `results/proxy.md` (the full generated report) and splices a short version of it into
`README.md` between the `<!-- AB-RESULTS -->` markers. Re-running it replaces the section rather
than appending, so it is safe to run every time another task lands.
"""
from __future__ import annotations

import io
import pathlib
import sys
from contextlib import redirect_stdout

from bench_agent import quick_report

BEGIN = "<!-- AB-RESULTS -->"
END = "<!-- /AB-RESULTS -->"


def render(dirs: list[str]) -> str:
    buf = io.StringIO()
    argv = sys.argv
    sys.argv = ["quick_report", *dirs]
    try:
        with redirect_stdout(buf):
            quick_report.main()
    finally:
        sys.argv = argv
    return buf.getvalue()


def main() -> int:
    dirs = sys.argv[1:]
    if len(dirs) != 2:
        print(__doc__)
        return 2
    report = render(dirs)

    results = pathlib.Path("results/proxy.md")
    results.parent.mkdir(exist_ok=True)
    results.write_text(
        "<!-- generated by `python -m bench_agent.publish`; do not edit by hand -->\n\n" + report)
    print(f"wrote {results}")

    # For the README keep the parts a reader needs in place, not the whole report.
    keep, taking = [], False
    for line in report.splitlines():
        if line.startswith("## Per task"):
            taking = False
        if line.startswith(("## Pooled", "## Per request", "## Paired")):
            taking = True
        if taking:
            keep.append(line)
    section = "\n".join(keep).strip()

    readme = pathlib.Path("README.md")
    text = readme.read_text()
    block = (f"{BEGIN}\n\n{section}\n\n"
             f"Full table, per task, including the arms' configs: "
             f"[`results/proxy.md`](results/proxy.md) — regenerate with "
             f"`python -m bench_agent.publish {' '.join(dirs)}`.\n\n{END}")
    if BEGIN in text and END in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        text = pre + block + post
    elif BEGIN in text:
        pre, post = text.split(BEGIN, 1)
        text = pre + block + post
    else:
        print(f"no {BEGIN} marker in README.md; wrote results/proxy.md only")
        return 0
    readme.write_text(text)
    print("spliced the A/B section into README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
